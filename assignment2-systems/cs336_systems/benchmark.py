"""Small, reusable benchmarking and PyTorch-profiling helpers.

The callable passed to :func:`benchmark` or :func:`profile` should perform one
complete unit of work, e.g. a forward pass, forward+backward, or a full training
step. Keeping setup outside the callable makes timing results comparable.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
import statistics
import time
from types import MappingProxyType

import torch
from torch import Tensor, nn

StepFunction = Callable[[], object]


@dataclass(frozen=True)
class ModelConfig:
    """Transformer dimensions for one of the handout's benchmark sizes."""

    d_model: int
    d_ff: int
    num_layers: int
    num_heads: int


MODEL_CONFIGS = MappingProxyType(
    {
        "small": ModelConfig(d_model=768, d_ff=3072, num_layers=12, num_heads=12),
        "medium": ModelConfig(d_model=1024, d_ff=4096, num_layers=24, num_heads=16),
        "large": ModelConfig(d_model=1280, d_ff=5120, num_layers=36, num_heads=20),
        "xl": ModelConfig(d_model=2560, d_ff=10240, num_layers=32, num_heads=32),
        "10b": ModelConfig(d_model=4608, d_ff=12288, num_layers=50, num_heads=36),
    }
)


def get_model_config(model_size: str) -> ModelConfig:
    """Return a handout model configuration, accepting case-insensitive names."""
    normalized = model_size.lower()
    try:
        return MODEL_CONFIGS[normalized]
    except KeyError as error:
        choices = ", ".join(MODEL_CONFIGS)
        raise ValueError(
            f"Unknown model size {model_size!r}; choose one of: {choices}"
        ) from error


@dataclass(frozen=True)
class BenchmarkResult:
    """Timing summary in milliseconds for one invocation of a step function."""

    samples_ms: tuple[float, ...]
    mean_ms: float
    std_ms: float


@dataclass(frozen=True)
class ProfileResult:
    """Summary generated by PyTorch Profiler for a single step function."""

    table: str
    trace_path: Path | None


def _synchronize(device: torch.device | str | None) -> None:
    """Synchronize CPU timing with CUDA only when the requested device is CUDA."""
    if device is None:
        return
    resolved = torch.device(device)
    if resolved.type == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError("A CUDA device was requested, but CUDA is unavailable.")
        torch.cuda.synchronize(resolved)


def benchmark(
    step_fn: StepFunction,
    *,
    warmup_steps: int = 5,
    measure_steps: int = 10,
    device: torch.device | str | None = "cuda",
) -> BenchmarkResult:
    """Warm up and accurately time repeated calls to ``step_fn``.

    CUDA launches are asynchronous, so synchronization occurs both before and
    after every measured call. ``step_fn`` owns model/data setup; it should not
    allocate a new model or random batch on every invocation.
    """
    if warmup_steps < 0:
        raise ValueError("warmup_steps must be non-negative")
    if measure_steps <= 0:
        raise ValueError("measure_steps must be positive")

    for _ in range(warmup_steps):
        step_fn()
    _synchronize(device)

    samples_ms: list[float] = []
    for _ in range(measure_steps):
        _synchronize(device)
        started = time.perf_counter()
        step_fn()
        _synchronize(device)
        samples_ms.append((time.perf_counter() - started) * 1_000)

    return BenchmarkResult(
        samples_ms=tuple(samples_ms),
        mean_ms=statistics.fmean(samples_ms),
        std_ms=statistics.stdev(samples_ms) if len(samples_ms) > 1 else 0.0,
    )


def profile(
    step_fn: StepFunction,
    *,
    warmup_steps: int = 5,
    profile_steps: int = 1,
    device: torch.device | str | None = "cuda",
    trace_path: str | Path | None = None,
    row_limit: int = 20,
    record_shapes: bool = True,
    profile_memory: bool = True,
    with_stack: bool = False,
) -> ProfileResult:
    """Profile one callable with ``torch.profiler`` and optionally export a trace.

    The returned table is sorted by self CUDA time for CUDA runs, otherwise by
    self CPU time. A trace exported here opens in Perfetto or ``chrome://tracing``.
    """
    if warmup_steps < 0:
        raise ValueError("warmup_steps must be non-negative")
    if profile_steps <= 0:
        raise ValueError("profile_steps must be positive")
    if row_limit <= 0:
        raise ValueError("row_limit must be positive")

    resolved = torch.device(device) if device is not None else torch.device("cpu")
    if resolved.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("A CUDA device was requested, but CUDA is unavailable.")

    for _ in range(warmup_steps):
        step_fn()
    _synchronize(resolved)

    activities = [torch.profiler.ProfilerActivity.CPU]
    if resolved.type == "cuda":
        activities.append(torch.profiler.ProfilerActivity.CUDA)

    with torch.profiler.profile(
        activities=activities,
        record_shapes=record_shapes,
        profile_memory=profile_memory,
        with_stack=with_stack,
    ) as profiler:
        for _ in range(profile_steps):
            step_fn()
            profiler.step()
    _synchronize(resolved)

    exported_path = Path(trace_path) if trace_path is not None else None
    if exported_path is not None:
        exported_path.parent.mkdir(parents=True, exist_ok=True)
        profiler.export_chrome_trace(str(exported_path))

    sort_by = (
        "self_cuda_time_total" if resolved.type == "cuda" else "self_cpu_time_total"
    )
    return ProfileResult(
        table=profiler.key_averages().table(sort_by=sort_by, row_limit=row_limit),
        trace_path=exported_path,
    )


def forward(
    model: nn.Module,
    inputs: Tensor,
):
    model.train()
    with torch.autocast(
        device_type="cuda", dtype=torch.bfloat16, enabled=inputs.device.type == "cuda"
    ):
        logits = model(inputs)


def forward_backward(
    model: nn.Module,
    optimizer: torch.optim.Optimizer,
    inputs: Tensor,
    targets: Tensor,
) -> Tensor:
    model.train()
    optimizer.zero_grad(set_to_none=True)

    with torch.autocast(
        device_type="cuda", dtype=torch.bfloat16, enabled=inputs.device.type == "cuda"
    ):
        logits = model(inputs)
        log_probs = torch.log_softmax(logits, dim=-1)
        loss = torch.nn.functional.nll_loss(log_probs, targets)

    loss.backward()
    return loss.detach()


def train_step(
    model: nn.Module,
    optimizer: torch.optim.Optimizer,
    inputs: Tensor,
    targets: Tensor,
) -> Tensor:
    """Run one forward, loss, backward, optional clipping, and optimizer step."""
    model.train()
    optimizer.zero_grad(set_to_none=True)

    with torch.autocast(
        device_type="cuda", dtype=torch.bfloat16, enabled=inputs.device.type == "cuda"
    ):
        logits = model(inputs)
        log_probs = torch.log_softmax(logits, dim=-1)
        loss = torch.nn.functional.nll_loss(log_probs, targets)

    loss.backward()
    optimizer.step()
    return loss.detach()
